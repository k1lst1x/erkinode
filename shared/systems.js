export const systems = Object.fromEntries(
  definitions.map(([id, name, family, icon]) => [id, { name, family, icon }]),
);
export const iconForSystem = (system) => {
  if (!system) return null;
  const direct = Object.hasOwn(systems, system.id) ? systems[system.id] : null;
  if (direct) return direct.icon;
  // A derivative with no dedicated artwork uses a known parent icon.
  for (const parent of system.like || [])
    if (
      Object.hasOwn(systems, parent) &&
      systems[parent].family === system.family
    )
      return systems[parent].icon;
  return (
    {
      linux: "linux",
      windows: "windows",
      macos: "macos",
      bsd: "unix",
      unix: "unix",
      network: "network",
      hypervisor: "network",
    }[system.family] || null
  );
};
